export function detectLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone;
  const language = navigator.languages?.[0] ?? navigator.language ?? "en";
  if (timeZone === "Asia/Seoul" || language.toLowerCase().startsWith("ko")) return "ko";
  if (timeZone === "Asia/Tokyo" || language.toLowerCase().startsWith("ja")) return "ja";
  return "en";
}

export function localeFromCoordinates(lat: number, lon: number): Locale | null {
  if (lat >= 32.5 && lat <= 39.8 && lon >= 124 && lon <= 132) return "ko";
  if (lat >= 24 && lat <= 46.5 && lon >= 122 && lon <= 146.5) return "ja";
  return null;
}
